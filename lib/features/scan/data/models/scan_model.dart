import '../../domain/entities/scan_entity.dart';

class ScanModel extends ScanEntity {
  const ScanModel({
    required super.id,
    required super.fullName,
    required super.email,
    required super.phone,
    required super.documentId,
    required super.cardNumber,
    required super.areaNames,
    super.areaId,
    required super.qrLink,
    required super.invitDocType,
    required super.name,
    required super.visitorImage,
    super.registrationDate,
    super.expiryDate,
    super.createDate,
    required super.status,
    required super.visitType,
    super.customVisitType,
    required super.createdUserId,
    required super.createdUserName,
    super.lastUpdatedUserId,
    super.updatedUserName,
    required super.isSuccess,
    required super.documentImage,
    super.transactionType,
    super.company,
    required super.statusValue,
  });

  factory ScanModel.fromJson(Map<String, dynamic> json) {
    return ScanModel(
      id: json['id']?.toString() ?? '',
      fullName: json['fullName']?.toString() ?? '',
      email: json['email']?.toString() ?? '',
      phone: json['phone']?.toString() ?? '',
      documentId: json['documentId']?.toString() ?? '',
      cardNumber: json['cardNumber']?.toString() ?? '',
      areaNames: json['areaNames']?.toString() ?? '',
      areaId: json['areaId'],
      qrLink: json['qrLink']?.toString() ?? '',
      invitDocType: int.tryParse(json['invitDocType']?.toString() ?? '') ?? 0,
      name: json['name']?.toString() ?? '',
      visitorImage: json['visitorImage']?.toString() ?? '',
      registrationDate: DateTime.tryParse(
        json['registrationDate']?.toString() ?? '',
      ),
      expiryDate: DateTime.tryParse(json['expiryDate']?.toString() ?? ''),
      createDate: DateTime.tryParse(json['createDate']?.toString() ?? ''),
      status: int.tryParse(json['status']?.toString() ?? '') ?? 0,
      visitType: json['visitType']?.toString() ?? '',
      customVisitType: json['customVisitType']?.toString(),
      createdUserId: json['createdUserId']?.toString() ?? '',
      createdUserName: json['createdUserName']?.toString() ?? '',
      lastUpdatedUserId: json['lastUpdatedUserId']?.toString(),
      updatedUserName: json['updatedUserName']?.toString(),
      isSuccess:
          json['isSuccess'] == true || json['isSuccess']?.toString() == '1',
      documentImage: json['documentImage']?.toString() ?? '',
      transactionType: json['transactionType']?.toString(),
      company: json['company']?.toString(),
      statusValue: json['statusValue']?.toString() ?? '',
    );
  }

  Map<String, dynamic> toJson() {
    return {
      'id': id,
      'fullName': fullName,
      'email': email,
      'phone': phone,
      'documentId': documentId,
      'cardNumber': cardNumber,
      'areaNames': areaNames,
      'areaId': areaId,
      'qrLink': qrLink,
      'invitDocType': invitDocType,
      'name': name,
      'visitorImage': visitorImage,
      'registrationDate': registrationDate?.toIso8601String(),
      'expiryDate': expiryDate?.toIso8601String(),
      'createDate': createDate?.toIso8601String(),
      'status': status,
      'visitType': visitType,
      'customVisitType': customVisitType,
      'createdUserId': createdUserId,
      'createdUserName': createdUserName,
      'lastUpdatedUserId': lastUpdatedUserId,
      'updatedUserName': updatedUserName,
      'isSuccess': isSuccess,
      'documentImage': documentImage,
      'transactionType': transactionType,
      'company': company,
      'statusValue': statusValue,
    };
  }
}
